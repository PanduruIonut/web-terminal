/**
 * Terminal colour themes.
 *
 * WHY EVERY COLOUR RULE IN HERE IS `!important`
 * ---------------------------------------------
 * The prompt characters, the echoed command, the `help` rows, the idle line and
 * the links are all painted from JavaScript in terminal-utils.ts — e.g.
 * `promptSpan1.style.color = "#ff9e64"`. Those are INLINE styles, and an inline
 * style beats every selector in a stylesheet no matter how specific it is. The
 * only thing that outranks an inline style is `!important`, so every declaration
 * below that has to fight one carries it. Remove the `!important` and the theme
 * silently does nothing to the prompt — the terminal keeps its Tokyo Night
 * orange/purple/cyan on a green background, which looks broken.
 *
 * (The page and terminal backgrounds are class-based, but they are also marked
 * `!important` because the site's own <style> block lives in the <body> — later
 * in the document than this one — and would otherwise win on source order.)
 */

export type ThemeName = "tokyo" | "phosphor" | "amber";

/** The single <style> element this module owns. Never duplicated. */
const STYLE_ID = "terminal-theme";

const NAMES: ThemeName[] = ["tokyo", "phosphor", "amber"];

interface Palette {
    /** html/body background. */
    readonly page: string;
    /** .terminal__content background (sits over `page`, so it may be translucent). */
    readonly body: string;
    readonly titleBar: string;
    readonly titleText: string;
    readonly titleBorder: string;
    readonly dotClose: string;
    readonly dotHide: string;
    readonly dotResize: string;
    /** λ — the brightest thing on screen. */
    readonly bright: string;
    /** Display text and the `~` segment. */
    readonly text: string;
    /** `>>` and the echoed command. */
    readonly mid: string;
    /** Path segment, help descriptions, idle nudge, hints. */
    readonly dim: string;
    readonly link: string;
    readonly caret: string;
    /** .terminal__input.valid-command */
    readonly ok: string;
    /** Phosphor bloom for ordinary text. */
    readonly glow: string;
    /** Phosphor bloom for the prompt. */
    readonly glowStrong: string;
    /** Scanline colour laid over the terminal body. Kept faint on purpose. */
    readonly scanline: string;
    /** Deadpan line the terminal prints back. */
    readonly status: string;
}

