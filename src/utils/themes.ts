/** Returns the single <style id="terminal-theme">, creating it once if needed. */
function themeStyleElement(): HTMLStyleElement {
    const existing = document.getElementById(STYLE_ID);
    if (existing instanceof HTMLStyleElement) return existing;
    if (existing) existing.remove();

    const element = document.createElement("style");
    element.id = STYLE_ID;
    document.head.appendChild(element);
    return element;
}

/**
 * Applies a theme and returns the line the terminal should print.
 * "tokyo" removes the override and restores the site default.
 */
const STORAGE_KEY = "terminal-theme";
const HINTS_STYLE_ID = "terminal-theme-hints";

/**
 * The hint line lives inside <my-hints>'s shadow root, so the document
 * stylesheet cannot reach it — a plain `.hints` rule there is dead CSS. Inject a
 * copy into the shadow root instead. Its two key spans get inline colours
 * rewritten on every rotation, so these need !important to stick.
 */
function paintHints(palette: Palette | null): void {
    const host = document.querySelector("my-hints");
    const root = host?.shadowRoot;
    if (!root) return;

    const existing = root.querySelector(`#${HINTS_STYLE_ID}`);

    if (!palette) {
        existing?.remove();
        return;
    }

    const style = existing instanceof HTMLStyleElement ? existing : document.createElement("style");
    style.id = HINTS_STYLE_ID;
    style.textContent = `
        .hints { color: ${palette.dim} !important; text-shadow: ${palette.glow} !important; }
        .hints span:nth-of-type(1) { color: ${palette.bright} !important; }
        .hints span:nth-of-type(2) { color: ${palette.mid} !important; }
    `;

    if (!style.isConnected) root.appendChild(style);
}

/**
 * <my-hints> is appended after the terminal, so on first load it does not exist
 * yet when the stored theme is restored. Retry briefly rather than racing it.
 */
function paintHintsWhenReady(palette: Palette | null): void {
    paintHints(palette);
    setTimeout(() => paintHints(palette), 0);
    setTimeout(() => paintHints(palette), 300);
}

/** Storage can throw in private mode, and a theme is not worth an exception. */
function remember(key: string): void {
    try {
        localStorage.setItem(STORAGE_KEY, key);
    } catch {
        /* ignore */
    }
}

export function applyTheme(name: string): string {
    const key = name.trim().toLowerCase();

    if (key === "tokyo") {
        const existing = document.getElementById(STYLE_ID);
        if (existing) existing.remove();
        paintHintsWhenReady(null);
        remember(key);
        return "theme: tokyo. Default restored. Nothing happened here.";
    }

    const palette = paletteFor(key);
    if (!palette) {
        return `Unknown theme '${name}'. Available: ${themeNames().join(", ")}.`;
    }

    themeStyleElement().textContent = buildCss(palette, key);
    paintHintsWhenReady(palette);
    remember(key);
    return palette.status;
}

/**
 * Reapplies the last chosen theme on load, so a reload does not silently throw
 * the choice away. Silent by design: nothing is printed to the terminal.
 */
export function restoreTheme(): void {
    let stored: string | null = null;
    try {
        stored = localStorage.getItem(STORAGE_KEY);
    } catch {
        return;
    }

    if (!stored || stored === "tokyo") return;

    const palette = paletteFor(stored);
    if (!palette) return;

    themeStyleElement().textContent = buildCss(palette, stored);
    paintHintsWhenReady(palette);
}

export function themeNames(): string[] {
    return [...NAMES];
}
